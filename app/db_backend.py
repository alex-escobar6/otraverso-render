from app.config import Config


NO_ID_TABLES = {
    "role_permissions", "settings", "product_related", "play_profiles",
    "play_achievements", "play_collectibles",
}


class CompatRow(Mapping):
    __slots__ = ("_keys", "_values")

    def __init__(self, keys: Sequence[str], values: Sequence[Any]):
        self._keys = tuple(keys)
        self._values = tuple(values)

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return self._values[key]
        return self._values[self._keys.index(key)]

    def __iter__(self):
        return iter(self._keys)

    def __len__(self) -> int:
        return len(self._keys)

    def keys(self):
        return self._keys

    def values(self):
        return self._values

    def items(self):
        return zip(self._keys, self._values)

    def __repr__(self) -> str:
        return f"CompatRow({dict(self.items())!r})"


def _row_factory(cursor):
    keys = [column.name for column in (cursor.description or [])]
    return lambda values: CompatRow(keys, values)


def adapt_sql(sql: str, *, ddl: bool = False) -> str:
    text = sql
    if ddl:
        text = re.sub(
            r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b",
            "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            text,
            flags=re.IGNORECASE,
        )
        text = re.sub(r"\bBLOB\b", "BYTEA", text, flags=re.IGNORECASE)
        text = re.sub(r"\s+COLLATE\s+NOCASE\b", "", text, flags=re.IGNORECASE)
        text = re.sub(
            r"\bDEFAULT\s+CURRENT_TIMESTAMP\b",
            "DEFAULT to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')",
            text,
            flags=re.IGNORECASE,
        )
    ignore = bool(re.search(r"\bINSERT\s+OR\s+IGNORE\b", text, flags=re.IGNORECASE))
    text = re.sub(r"\bINSERT\s+OR\s+(?:IGNORE|REPLACE)\b", "INSERT", text, flags=re.IGNORECASE)
    text = re.sub(
        r"datetime\(\s*'now'\s*\)",
        "to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(
        r"datetime\(\s*'now'\s*,\s*'-(\d+)\s+(hour|day|minute)s?'\s*\)",
        lambda m: "to_char(CURRENT_TIMESTAMP - INTERVAL '" + m.group(1) + " " + m.group(2) + "', 'YYYY-MM-DD HH24:MI:SS')",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(r"date\(\s*'now'\s*\)", "CURRENT_DATE", text, flags=re.IGNORECASE)
    text = re.sub(
        r"date\(\s*'now'\s*,\s*'-(\d+)\s+(hour|day|minute)s?'\s*\)",
        lambda m: "CAST(CURRENT_DATE - INTERVAL '" + m.group(1) + " " + m.group(2) + "' AS DATE)",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(r"\bdate\(\s*([a-zA-Z_][\w.]*|\?)\s*\)", r"CAST(\1 AS DATE)", text, flags=re.IGNORECASE)
    text = text.rstrip().rstrip(";")
    if ignore and "ON CONFLICT" not in text.upper():
        text += " ON CONFLICT DO NOTHING"
    return text.replace("?", "%s")


class CompatCursor:
    def __init__(self, cursor):
        self._cursor = cursor
        self._prefetch = None
        self.lastrowid = 0
        self._rowcount = 0

    @property
    def rowcount(self) -> int:
        return self._rowcount

    @property
    def description(self):
        return self._cursor.description

    def execute(self, sql: str, params: Iterable[Any] = ()) -> "CompatCursor":
        statement = adapt_sql(sql)
        insert = bool(re.match(r"^\s*INSERT\b", statement, flags=re.IGNORECASE))
        table_match = re.search(r"^\s*INSERT\s+INTO\s+([a-zA-Z_]\w*)", statement, flags=re.IGNORECASE)
        table = table_match.group(1).lower() if table_match else ""
        returning = "RETURNING" in statement.upper()
        wants_id = insert and not returning and table not in NO_ID_TABLES
        if wants_id:
            statement += " RETURNING id"
        self._cursor.execute(statement, tuple(params))
        self._rowcount = self._cursor.rowcount
        if wants_id:
            row = self._cursor.fetchone()
            self.lastrowid = row[0] if row else 0
        return self

    def executemany(self, sql: str, params: Iterable[Iterable[Any]]) -> "CompatCursor":
        self._cursor.executemany(adapt_sql(sql), [tuple(row) for row in params])
        self._rowcount = self._cursor.rowcount
        return self

    def fetchone(self):
        if self._prefetch is not None:
            value = self._prefetch
            self._prefetch = None
            return value
        return self._cursor.fetchone()

    def fetchall(self):
        first = [] if self._prefetch is None else [self._prefetch]
        self._prefetch = None
        return first + list(self._cursor.fetchall())

    def __iter__(self):
        return iter(self.fetchall())


class CompatConnection:
    def __init__(self, connection):
        self._connection = connection
        self._connection.row_factory = _row_factory

    @property
    def closed(self) -> bool:
        return self._connection.closed

    def execute(self, sql: str, params: Iterable[Any] = ()) -> CompatCursor:
        return CompatCursor(self._connection.cursor()).execute(sql, params)

    def executemany(self, sql: str, params: Iterable[Iterable[Any]]) -> CompatCursor:
        return CompatCursor(self._connection.cursor()).executemany(sql, params)

    def executescript(self, sql: str) -> None:
        self._connection.execute(adapt_sql(sql, ddl=True))

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        self._connection.close()

    def __enter__(self) -> "CompatConnection":
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        try:
            if exc_type is None:
                self.commit()
            else:
                self.rollback()
        finally:
            self.close()


def connect():
    if Config.DB_BACKEND != "postgres":
        raise RuntimeError("connect_postgres() llamado sin DATABASE_URL")
    import psycopg

    parsed = urllib.parse.urlsplit(Config.DATABASE_URL)
    query = dict(urllib.parse.parse_qsl(parsed.query, keep_blank_values=True))
    query.setdefault("sslmode", "require")
    if "hostaddr" not in query and parsed.hostname:
        try:
            addresses = socket.getaddrinfo(parsed.hostname, parsed.port or 5432, socket.AF_INET, socket.SOCK_STREAM)
        except OSError:
            addresses = []
        if addresses:
            query["hostaddr"] = addresses[0][4][0]
    target = urllib.parse.urlunsplit((
        parsed.scheme, parsed.netloc, parsed.path, urllib.parse.urlencode(query), parsed.fragment
    ))
    connection = psycopg.connect(target)
    return CompatConnection(connection)


def init_schema(conn, schema_sql: str, version: int) -> None:
    conn.executescript(schema_sql)
    conn.execute("CREATE TABLE IF NOT EXISTS app_meta(key TEXT PRIMARY KEY, value TEXT NOT NULL)")
    conn.execute(
        "INSERT INTO app_meta(key,value) VALUES ('schema_version',%s) "
        "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
        (str(version),),
    )


def table_columns(conn, table: str) -> set[str]:
    if hasattr(conn, "_connection"):
        rows = conn.execute(
            "SELECT column_name FROM information_schema.columns "
            "WHERE table_schema=current_schema() AND table_name=%s",
            (table,),
        ).fetchall()
        return {row[0] for row in rows}
    return {row[1] for row in conn.execute(f"PRAGMA table_info({table})")}


def schema_version(conn) -> int:
    if hasattr(conn, "_connection"):
        row = conn.execute("SELECT value FROM app_meta WHERE key='schema_version'").fetchone()
        return int(row[0]) if row else 0
    return int(conn.execute("PRAGMA user_version").fetchone()[0])
