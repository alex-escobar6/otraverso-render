def list_games(status: str = "") -> list[dict]:
    return [dict(game) for game in GAMES.values() if not status or game["status"] == status]


def get_game(code: str) -> dict | None:
    game = GAMES.get(code)
    return dict(game) if game else None


def get_manifest(code: str) -> dict | None:
    game = get_game(code)
    if not game:
        return None
    return {
        "id": game["code"],
        "code": game["code"],
        "name": game["name"],
        "version": game["version"],
        "status": game["status"],
        "category": game["category"],
        "world": game["world"],
        "route": game["route"],
        "entry": game["entry"],
        "css": list(game["css"]),
        "dependencies": list(game.get("dependencies", [])),
        "engine": dict(game["engine"]),
        "capabilities": list(game["capabilities"]),
        "budgets": dict(game["budgets"]),
        "tagline": game.get("tagline", ""),
        "description": game.get("description", ""),
        "accent": game.get("accent", "#67e8f9"),
        "hub": dict(game.get("hub", {})),
    }


def published_codes() -> set[str]:
    return {code for code, game in GAMES.items() if game["status"] == "published"}
